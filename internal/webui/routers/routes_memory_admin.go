package webuiapi

// WebUI memory 管理路由挂载；对齐 memory.py 的 router(/api/webui/memory) 与
// compat_router(/api) 两棵真实路径树。由 Lead 在根 mux 调用一次

import (
	"github.com/go-chi/chi/v5"
)

// mountMemoryAdminRoutes 注册 memory.py 的全部路由
func mountMemoryAdminRoutes(root chi.Router, d Deps) {
	root.Route("/api/webui/memory", func(mr chi.Router) {
		mr.Use(memoryAdminAuth(d))
		mountMemoryWebUIRoutes(mr, d)
	})
	root.Route("/api", func(ar chi.Router) {
		ar.Use(memoryAdminAuth(d))
		mountMemoryCompatRoutes(ar, d)
	})
}

