// ModuleDisplayName 返回模块的中文别名，未命中时返回原名
// 对齐 Python logger.py:704 的 MODULE_ALIASES.get(logger_name, logger_name)
func ModuleDisplayName(name string) string {
	if alias, ok := moduleAliases[name]; ok && alias != "" {
		return alias
	}
	return name
}

// ModuleColor 返回模块颜色，未命中时返回零值
// 对齐 Python logger.py:699 的 MODULE_COLORS.get(logger_name, "")
func ModuleColor(name string) moduleColor {
	return moduleColors[name]
}
